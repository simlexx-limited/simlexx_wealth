import asyncio
import logging

import openai
from pathlib import Path

from google.genai.types import Content, Part
from google.adk.runners import Runner
from google.adk.sessions import InMemorySessionService

from app.ai_agents.llm.llm_definition import LLMDefinition
from app.ai_agents.prompts.recommender import instructions, prompts
from app.config.setting import get_settings

REPO_ROOT = Path(__file__).parent.parent.parent
LOGS_DIR = REPO_ROOT / "server_logs"
ERRORS_LOG_PATH = LOGS_DIR / "errors.log"
LOGS_DIR.mkdir(parents=True, exist_ok=True)

logger = logging.getLogger(__name__)

class Agents:
    def __init__(
            self,
            instructions:str,
            prompts:str,
            agent_builder:str
            ):
        self.instructions = instructions
        self.prompts = prompts
        self.agent_builder = agent_builder
        self.settings = get_settings()
        self.llm_definition = LLMDefinition(
            instructions=self.instructions,
            prompts=self.prompts
            )
        self.session_service = InMemorySessionService()

    async def build(self, agent_name:str = "learning_llm"):
        build_method = getattr(
            self.llm_definition,
            self.agent_builder
            )
        return await build_method(agent_name=agent_name)

    async def __run_with_agent(self, agent, user_id:str) -> str:
        runner = Runner(
            agent=agent,
            app_name=self.settings.APP_NAME,
            session_service=self.session_service
            )

        session = await self.session_service.create_session(
            app_name=self.settings.APP_NAME,
            user_id=user_id
            )
        message = Content(
            role="user",
            parts=[Part(text=self.prompts)]
            )

        final_text = ""
        async for event in runner.run_async(user_id=user_id, session_id=session.id, new_message=message):
            if event.model_version:
                logger.info("Response generated by model: %s", event.model_version)
            if event.finish_reason:
                logger.info("Generation finish_reason: %s", event.finish_reason)
            if event.is_final_response() and event.content:
                final_text = "".join(part.text for part in event.content.parts if part.text)

        return final_text

    async def run(self, user_id:str, agent_name:str) -> str:
        """Build the agent once and run one turn with the configured prompt,
        returning the final response text. Retries the same model a few
        times on a transient failure (rate limit, connection error, etc.)."""
        agent = await self.build(agent_name=agent_name)

        last_error = None
        for attempt in range(1, self.settings.LLM_MAX_RETRIES + 1):
            try:
                return await self.__run_with_agent(agent, user_id=user_id)
            except openai.APIError as error:
                last_error = error
                if attempt < self.settings.LLM_MAX_RETRIES:
                    logger.warning(
                        "LLM call attempt %d/%d failed (%s), retrying in %ds...",
                        attempt, self.settings.LLM_MAX_RETRIES, error, self.settings.LLM_RETRY_DELAY,
                        )
                    await asyncio.sleep(self.settings.LLM_RETRY_DELAY)
        raise last_error
